// Line ids: ch1.pro.NN (prologue), ch1.sN.bNN (briefing, over live play),
// ch1.sN.cNN (cutscene), ch1.epi.NN (epilogue), ch1.bark.<key>.N.
// Ids are written out by hand so that reordering or inserting a line never
// renames its neighbours: the voice cache is keyed on them.
//
// Staging persists (bg, on) until a later line changes it. Thorne is never in
// `on` unless the backdrop is 'line': over any other backdrop she is a voice
// in Ren's ear and nobody else on stage can hear her.

